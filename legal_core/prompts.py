def format_history(history, limit=8):
    lines = []
    for message in (history or [])[-limit:]:
        role = "Пользователь" if message.get("role") == "user" else "Ассистент"
        lines.append(f"{role}: {message.get('content', '')}")
    return "\n".join(lines) or "нет"


def context_header(item, period=None):
    status = item.get("edition") or ("действующая редакция" if item.get("doc_type") == "law" else "")
    status = f" [{status}]" if status else ""
    note = applicability_note(item, period)
    note = f" [{note}]" if note else ""
    return f"[{item['label']}] {item.get('doc_display') or item['doc_title']}{status}{note} — {item['citation']}"


def format_context(context, period=None):
    return "\n\n".join(f"{context_header(item, period)}\n{item['text']}" for item in context)


def date_line(period):
    """Строка о дате события для генерации и проверки: какую редакцию применять."""
    if not period:
        return ""
    return (f"Дата события из вопроса: {period['label']}. Применяй редакции документов, которые действовали "
            f"на эту дату (в заголовках фрагментов: «ПРИМЕНЯЕТСЯ к событию»). Редакции с пометкой «НЕ ПРИМЕНЯЕТСЯ» "
            f"не используй для ответа; их можно упомянуть одной фразой как отличие действующих правил.\n")


def generate_messages(question, history, context, period=None):
    user = (
        f"<history>\n{format_history(history)}\n</history>\n"
        f"<user_input>\n{question}\n</user_input>\n{date_line(period)}"
        f"<context>\n{format_context(context, period)}\n</context>"
    )
    return [{"role": "system", "content": GENERATE_SYSTEM}, {"role": "user", "content": user}]


def review_messages(question, history, context, draft, hints, period=None):
    hint_text = ("Автоматическая проверка нашла возможные проблемы:\n- " + "\n- ".join(hints)) if hints else ""
    system = REVIEW_SYSTEM.replace("{hints}", hint_text)
    user = (
        f"<history>\n{format_history(history)}\n</history>\n"
        f"<user_input>\n{question}\n</user_input>\n{date_line(period)}"
        f"<context>\n{format_context(context, period)}\n</context>\n"
        f"<draft>\n{draft}\n</draft>"
    )
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def analyze_messages(question, history):
    user = f"<history>\n{format_history(history)}\n</history>\n<user_input>\n{question}\n</user_input>"
    return [{"role": "system", "content": ANALYZE_SYSTEM}, {"role": "user", "content": user}]


