def lean_messages(question, history, context, period=None):
    dialog = "".join(f"{'Пользователь' if t['role'] == 'user' else 'Ассистент'}: {t['content']}\n" for t in history)
    user = (
        (f"<dialog>\n{dialog}</dialog>\n" if dialog else "")
        + f"<user_input>\n{question}\n</user_input>\n{date_line(period)}"
        + f"<context>\n{format_context(context, period)}\n</context>"
    )
    return [{"role": "system", "content": LEAN_SYSTEM}, {"role": "user", "content": user}]
