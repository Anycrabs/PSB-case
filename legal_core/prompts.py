def format_history(history, limit=8):
    lines = []
    for message in (history or [])[-limit:]:
        role = "Пользователь" if message.get("role") == "user" else "Ассистент"
        lines.append(f"{role}: {message.get('content', '')}")
    return "\n".join(lines) or "нет"


def context_header(item):
    status = item.get("edition") or ("действующая редакция" if item.get("doc_type") == "law" else "")
    status = f" [{status}]" if status else ""
    return f"[{item['label']}] {item.get('doc_display') or item['doc_title']}{status} — {item['citation']}"


def format_context(context):
    return "\n\n".join(f"{context_header(item)}\n{item['text']}" for item in context)


def generate_messages(question, history, context, event_date=None):
    date_line = f"Дата события (по разбору вопроса): {event_date}\n" if event_date else ""
    user = (
        f"<history>\n{format_history(history)}\n</history>\n"
        f"<user_input>\n{question}\n</user_input>\n{date_line}"
        f"<context>\n{format_context(context)}\n</context>"
    )
    return [{"role": "system", "content": GENERATE_SYSTEM}, {"role": "user", "content": user}]


def review_messages(question, history, context, draft, hints):
    hint_text = ("Автоматическая проверка нашла возможные проблемы:\n- " + "\n- ".join(hints)) if hints else ""
    system = REVIEW_SYSTEM.replace("{hints}", hint_text)
    user = (
        f"<history>\n{format_history(history)}\n</history>\n"
        f"<user_input>\n{question}\n</user_input>\n"
        f"<context>\n{format_context(context)}\n</context>\n"
        f"<draft>\n{draft}\n</draft>"
    )
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def analyze_messages(question, history):
    user = f"<history>\n{format_history(history)}\n</history>\n<user_input>\n{question}\n</user_input>"
    return [{"role": "system", "content": ANALYZE_SYSTEM}, {"role": "user", "content": user}]
